import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { chromium } from 'playwright'

const browser = await chromium.launch({ channel: 'chrome', headless: true })
const checks = [], errors = [], samples = []
await mkdir('docs/art-screenshots', { recursive: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
page.on('pageerror', error => errors.push(error.message))
const sound = () => page.evaluate(() => window.__islandSoundInspect())
const shot = name => page.screenshot({ path: `docs/art-screenshots/${name}.png` })
const waitIdle = () => page.getByRole('button', { name: '跳过动画', exact: true }).waitFor({ state: 'detached', timeout: 20000 })
try {
  await page.goto('http://127.0.0.1:5186/')
  await page.getByText('三维小岛加载完成', { exact: true }).waitFor()
  await page.waitForTimeout(7000)
  assert.equal((await sound()).contextState, 'uninitialized')
  assert.equal((await sound()).enabled, false)
  await shot('01-island')
  await page.getByRole('button', { name: '近看', exact: true }).click()
  await page.waitForTimeout(1000)
  await shot('02-details')
  await page.getByRole('button', { name: '开启声音', exact: true }).click()
  await page.waitForFunction(() => window.__islandSoundInspect().contextState === 'running')
  assert.equal((await sound()).contextState, 'running')
  const pose = await page.evaluate(() => window.__islandInspect().camera)
  await page.getByRole('button', { name: /看进账合成/ }).click()
  await page.waitForFunction(() => window.__reserveInspect?.().pieces.some(piece => piece.kind === 'gold' && !piece.spent), undefined, { timeout: 8000 })
  await shot('03-merge')
  await waitIdle()
  const merged = await sound()
  assert.ok(merged.played > 0)
  assert.ok(merged.peakVoices <= 6)
  assert.equal(merged.voices, 0)
  samples.push({ moment: 'merge', ...merged })
  assert.deepEqual(await page.evaluate(() => window.__islandInspect().camera), pose)
  await page.getByRole('button', { name: /看出账拆分/ }).click()
  await page.waitForTimeout(220)
  await shot('04-fracture')
  await waitIdle()
  const split = await sound()
  assert.ok(split.played > merged.played)
  samples.push({ moment: 'fracture', ...split })
  checks.push('Default silent; trusted toggle unlocks real AudioContext; physical merge and fracture emit bounded audio; natural completion clears voices; camera unchanged')
  await page.getByRole('button', { name: /看进账合成/ }).click()
  await page.waitForTimeout(450)
  await page.getByRole('button', { name: '跳过动画', exact: true }).click()
  await page.waitForTimeout(100)
  assert.equal((await sound()).voices, 0)
  await page.getByRole('button', { name: '关闭声音', exact: true }).click()
  const played = (await sound()).played
  await page.getByRole('button', { name: /看出账拆分/ }).click()
  await waitIdle()
  assert.equal((await sound()).played, played)
  await page.reload()
  await page.getByText('三维小岛加载完成', { exact: true }).waitFor()
  assert.equal((await sound()).enabled, false)
  checks.push('Skipping stops active sound, mute suppresses new sounds, mute preference survives reload')
  await page.getByRole('button', { name: '背面', exact: true }).click()
  await page.waitForTimeout(1100); await shot('05-back')
  await page.getByRole('button', { name: '回到初始视角', exact: true }).click()
  await page.waitForTimeout(1100)
  const before = await page.evaluate(() => window.__islandInspect().camera)
  await page.getByRole('button', { name: /看进账合成/ }).click()
  await waitIdle()
  assert.deepEqual(await page.evaluate(() => window.__islandInspect().camera), before)
  checks.push('Home-distance transaction remains in the chosen view')
  await page.getByRole('button', { name: '打开设置', exact: true }).click()
  await page.getByLabel('小岛音效', { exact: true }).check()
  await page.getByLabel('减少动态效果', { exact: true }).check()
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  assert.equal((await sound()).reduced, true)
  assert.equal((await sound()).voices, 0)
  checks.push('Reduced-motion preference also silences foley')
  for (const [width, height] of [[1180, 820], [390, 844], [360, 800]]) {
    await page.setViewportSize({ width, height }); await page.waitForTimeout(400)
    const layout = await page.evaluate(() => {
      const panel = document.querySelector('.study-panel'), submit = document.querySelector('.transaction-submit').getBoundingClientRect()
      return { document: document.documentElement.scrollWidth, viewport: innerWidth, panelOverflow: panel.scrollHeight - panel.clientHeight, submitBottom: submit.bottom }
    })
    assert.ok(layout.document <= width)
    if (width < 760) assert.ok(layout.submitBottom <= height, JSON.stringify(layout))
    else assert.ok(layout.panelOverflow <= 1, JSON.stringify(layout))
    samples.push({ width, height, ...layout })
    await shot(`06-responsive-${width}`)
  }
  checks.push('1180 desktop panel fits; 390/360 mobile transaction button fits first screen; no horizontal overflow')
  assert.deepEqual(errors, [])
  await writeFile('docs/art-audio-check.json', JSON.stringify({ checkedAt: new Date().toISOString(), checks, samples, errors }, null, 2) + '\n')
  console.log(JSON.stringify({ checks, samples, errors }, null, 2))
} finally { await browser.close() }
